#!/usr/bin/env python3
"""Generate src/core/tzdata.c, the time zone database built into Rayforce.

Development utility, standard library only; needs `zic` on the PATH. Run once
a release, on the newest archive from https://www.iana.org/time-zones, after
checking the archive against its published signature:

    make tzdata TZDATA=path/to/tzdata2026f.tar.gz

It compiles the archive's zones with `zic -b slim`, stores each distinct TZif
file once, and writes them as one byte array with an index sorted by name.
"""
import argparse
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

# What a distribution ships: the regions, the Etc zones and the old names.
# Not `factory` (a placeholder zone) nor `backzone` (pre-1970 alternatives).
SOURCES = ["africa", "antarctica", "asia", "australasia", "europe",
           "northamerica", "southamerica", "etcetera", "backward"]


def compile_zones(archive: Path, work: Path) -> tuple[str, dict[str, bytes]]:
    src, out = work / "src", work / "out"
    src.mkdir()
    with tarfile.open(archive) as tar:
        for name in SOURCES + ["version"]:
            member = tar.extractfile(name)
            if member is None:
                sys.exit(f"{archive}: no file {name}")
            (src / name).write_bytes(member.read())
    version = (src / "version").read_text().strip()
    subprocess.run(["zic", "-b", "slim", "-d", str(out)] + [str(src / s) for s in SOURCES], check=True)
    zones = {p.relative_to(out).as_posix(): p.read_bytes() for p in out.rglob("*") if p.is_file()}
    return version, zones


def render(version: str, zones: dict[str, bytes], header: str) -> str:
    blob = bytearray()
    at: dict[bytes, int] = {}
    rows = []
    for name in sorted(zones, key=str.encode):   # strcmp order, which the lookup searches
        data = zones[name]
        if data not in at:
            at[data] = len(blob)
            blob += data
        rows.append(f'    {{"{name}", {at[data]}, {len(data)}}},')
    lines = [",".join(str(b) for b in blob[i:i + 24]) + "," for i in range(0, len(blob), 24)]
    return "\n".join([
        header,
        f"/* Generated by scripts/gen-tzdata.py from the IANA time zone database {version}.",
        " * Do not edit: run `make tzdata` on a newer archive.  The database is in the",
        " * public domain. */",
        "",
        '#include "core/tz.h"',
        "",
        f'const char ray_tzdata_version[] = "{version}";',
        "",
        f"const int32_t ray_tzdata_count = {len(rows)};",
        "",
        "const ray_tzdata_zone_t ray_tzdata_zones[] = {",
        *rows,
        "};",
        "",
        "const uint8_t ray_tzdata_blob[] = {",
        *lines,
        "};",
        "",
    ])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("archive", type=Path, help="tzdataYYYYx.tar.gz from IANA")
    ap.add_argument("-o", "--out", type=Path, default=Path("src/core/tzdata.c"))
    args = ap.parse_args()
    # The licence block every source file opens with, taken from a sibling.
    sibling = (args.out.parent / "tz.c").read_text()
    header = sibling[:sibling.index("*/") + 2] + "\n"
    with tempfile.TemporaryDirectory() as work:
        version, zones = compile_zones(args.archive, Path(work))
    args.out.write_text(render(version, zones, header))
    print(f"{args.out}: tzdata {version}, {len(zones)} names, {len(set(zones.values()))} zones")


if __name__ == "__main__":
    main()
